// RC7 (ADR-0066): generates the forecaster agent's key into the repo's `.env` once, as
// RECEIPTS_AGENT_KEY. The value is never printed; only the agent's address is.
//   bun scripts/agent-key.ts
import { appendFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Ed25519Keypair } from "@mysten/sui/keypairs/ed25519";
import { keypairFrom } from "../src/keys.ts";

const envPath = join(dirname(fileURLToPath(import.meta.url)), "../../../.env");
const text = readFileSync(envPath, "utf8");
const has = /^RECEIPTS_AGENT_KEY=.+/m.test(text);
if (!has) {
  appendFileSync(
    envPath,
    `\n# Receipts (U12, ADR-0066): the reference forecaster agent's key, generated by apps/receipts/scripts/agent-key.ts\nRECEIPTS_AGENT_KEY=${Ed25519Keypair.generate().getSecretKey()}\n`,
  );
}
const raw = /^RECEIPTS_AGENT_KEY=(.+)$/m.exec(readFileSync(envPath, "utf8"))?.[1];
console.log(
  "agent",
  keypairFrom(raw, "RECEIPTS_AGENT_KEY").toSuiAddress(),
  has ? "(already set)" : "(generated)",
);
